#!/usr/bin/env python3
"""Regenerate .hermes/profiles/*/ from .claude/agents/*.md.

Hermes has no project-scoped agent files. Its unit of "agent" is a profile, and a
profile directory holding `distribution.yaml` + `SOUL.md` installs with
`hermes profile install`. Run this after editing any file in .claude/agents/.
Skills need no port: Hermes loads `.agents/skills/` of a trusted git root natively.
"""
import argparse
import json
import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / ".claude" / "agents"
DST = ROOT / ".hermes" / "profiles"

GENERATED = {"SOUL.md", "distribution.yaml"}

RUNTIME = """<!-- Generated by .hermes/sync-agents.py from the Claude agent source -- do not edit. -->

## Hermes runtime notes

Everything after these notes is the Claude Code prompt for `{stem}` verbatim. Where it says:

- "the Agent tool", "the Task tool", "spawn" -- use `delegate_task`. With `delegation.backend` set to
  `profile_routes` and this agent's profile listed under `delegation.backends.profile_routes`, route the
  task to the profile named `<agent-name>`; the child then runs with that profile's `SOUL.md`. Without
  that route, put "Act as `<agent-name>`: read `.hermes/profiles/<agent-name>/SOUL.md` first, then do
  the task" at the top of the goal and pass the needed context. A delegated child cannot delegate further.
- "subagent_type" -- the agent name, written into the `delegate_task` goal as above.
- "TodoWrite", "TaskCreate", "TaskList", "the shared task list" -- use the `todo_list` tool.
- "SendMessage", "the mailbox", "Claude Code Agent Teams", `TeamCreate` -- not available. Use the
  documented one-shot fallback: one `delegate_task` per handoff, sequenced by you.
- "the Skill tool" -- use `skill_view`. Repository skills load from `.agents/skills/` when the
  project root is trusted (`hermes skills trust`); run Hermes from inside the repository.
"""

SKILLS = """
## Load these skills first

Hermes does not preload skills from a profile. Before you start work, load each of these with
`skill_view`: {names}. Their rules bind you exactly as if written here.
"""


def split(path):
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", path.read_text(), re.S)
    if not m:
        sys.exit(f"no frontmatter in {path}")
    return m.group(1), m.group(2)


def description(head):
    for line in head.split("\n"):
        if line.startswith("description:"):
            value = line.split(":", 1)[1].strip()
            if value.startswith('"'):
                value = json.loads(value)
            first = re.split(r"(?<=[.!?])\s", value, maxsplit=1)[0]
            return first[:240]
    return ""


def skills_of(head):
    skills, on = [], False
    for line in head.split("\n"):
        if on:
            if line.startswith("  - "):
                skills.append(line[4:].strip())
                continue
            on = False
        if line.startswith("skills:"):
            on = True
    return skills


def convert(path):
    head, body = split(path)
    stem = path.stem
    soul = RUNTIME.format(stem=stem)
    skills = skills_of(head)
    if skills:
        soul += SKILLS.format(names=", ".join(f"`{s}`" for s in skills))
    soul += "\n" + body
    manifest = (
        "# Generated by .hermes/sync-agents.py -- do not edit.\n"
        f"name: {stem}\n"
        'version: "1.0.0"\n'
        f"description: {json.dumps(description(head), ensure_ascii=False)}\n"
        "distribution_owned:\n"
        "  - SOUL.md\n"
        "  - distribution.yaml\n"
    )
    return {"SOUL.md": soul, "distribution.yaml": manifest}


def expected_outputs():
    return {
        DST / src.stem / name: content
        for src in sorted(SRC.glob("*.md"))
        for name, content in convert(src).items()
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated profiles are stale")
    args = parser.parse_args()

    expected = expected_outputs()
    actual = {p for d in DST.glob("*") if d.is_dir() for p in d.iterdir()} if DST.is_dir() else set()
    unexpected = actual - set(expected)
    drifted = [p for p, c in expected.items() if not p.is_file() or p.read_text() != c]

    if args.check:
        for path in sorted(drifted):
            print(f"stale: {path.relative_to(ROOT)}")
        for path in sorted(unexpected):
            print(f"unexpected: {path.relative_to(ROOT)}")
        if drifted or unexpected:
            return 1
        print(f"{len(expected) // len(GENERATED)} Hermes profile(s) valid and in sync")
        return 0

    for stale in sorted(unexpected):
        shutil.rmtree(stale) if stale.is_dir() else stale.unlink()
    for path, content in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    for stem in sorted({p.parent.name for p in expected}):
        print(f"{stem} -> .hermes/profiles/{stem}/")
    if DST.is_dir():
        for d in DST.iterdir():
            if d.is_dir() and d.name not in {p.parent.name for p in expected}:
                shutil.rmtree(d)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
